#!/usr/bin/env python3
"""Session Broadcast Hook - PostToolUse event broadcasting for GRIP pair mode."""

import json
import os
import re
import socket
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
sys.path.insert(0, str(Path.home() / ".claude" / "lib"))
from hook_utils import parse_hook_input, respond
from _compat import grip_socket_path, grip_instance_path

# High-impact tools worth broadcasting
HIGH_IMPACT_TOOLS = {"Bash", "Write", "Edit", "Skill", "TeamCreate", "SendMessage"}

# Secret patterns to redact from payloads
SECRET_PATTERN = re.compile(r"(?:sk-|pk_|ghp_|gho_|xox[bpras]-)[A-Za-z0-9_-]+")

# Payload size limits (generous for pair-mode code review)
MAX_INPUT_LENGTH = 5000
MAX_OUTPUT_LENGTH = 10000

# Socket connection timeout
SOCKET_TIMEOUT = 1.0


def sanitize_value(value: str, max_length: int) -> str:
    """Truncate and redact secrets from a string value."""
    if not isinstance(value, str):
        value = json.dumps(value) if value is not None else ""
    # Redact secrets
    value = SECRET_PATTERN.sub("[REDACTED]", value)
    # Truncate
    if len(value) > max_length:
        value = value[:max_length] + f"... [truncated, {len(value)} total]"
    return value


def sanitize_input(tool_input: dict) -> dict:
    """Sanitize tool input, redacting secrets and truncating large values."""
    if not isinstance(tool_input, dict):
        return {}
    sanitized = {}
    for key, value in tool_input.items():
        if isinstance(value, str):
            sanitized[key] = sanitize_value(value, MAX_INPUT_LENGTH)
        elif isinstance(value, dict):
            sanitized[key] = sanitize_input(value)
        else:
            sanitized[key] = value
    return sanitized


# Unix domain sockets: available on macOS, Linux, and Windows 10 build 17063+ (Python 3.9+)
_UNIX_SOCKETS_AVAILABLE = hasattr(socket, "AF_UNIX")


def broadcast_event(socket_path: str, event: dict) -> bool:
    """Send event to session control server via Unix socket. Non-blocking.

    Returns False immediately on platforms without AF_UNIX support.
    """
    if not _UNIX_SOCKETS_AVAILABLE:
        return False
    try:
        sock = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)  # type: ignore[attr-defined]
        sock.settimeout(SOCKET_TIMEOUT)
        sock.connect(socket_path)
        message = json.dumps(event) + "\n"
        sock.sendall(message.encode("utf-8"))
        sock.close()
        return True
    except Exception:
        return False


def _get_claude_code_pid() -> int:
    """Get the Claude Code (node) process PID from the process tree.

    Hook runs as: Claude Code (node) -> shell -> python3 (this hook).
    The grandparent PID is Claude Code's PID, which matches the 'pid' field
    in session lock files.

    Returns 0 if grandparent PID cannot be determined.
    """
    import subprocess as _sp

    shell_pid = os.getppid()
    try:
        # ps -o ppid= -p <pid> returns the parent PID of the given process
        result = _sp.run(
            ["ps", "-o", "ppid=", "-p", str(shell_pid)],
            capture_output=True, text=True, timeout=2,
        )
        if result.returncode == 0 and result.stdout.strip():
            return int(result.stdout.strip())
    except (ValueError, OSError, _sp.TimeoutExpired):
        pass
    return 0


# Cached instance UUID (avoids repeated file reads per hook call)
_cached_instance_uuid: str | None = None


def _get_instance_uuid() -> str:
    """Get the per-instance UUID for this Claude Code session.

    Reads grip-instance-{grandparent_pid}.id from the OS temp dir, generated by session-start.sh.
    Cached after first lookup.
    """
    global _cached_instance_uuid
    if _cached_instance_uuid is not None:
        return _cached_instance_uuid

    claude_pid = _get_claude_code_pid()
    if claude_pid:
        id_file = Path(grip_instance_path(claude_pid))
        if id_file.exists():
            try:
                _cached_instance_uuid = id_file.read_text().strip()
                return _cached_instance_uuid
            except OSError:
                pass

    _cached_instance_uuid = ""
    return ""


def _discover_from_socket_glob(claude_pid: int) -> str:
    """Discover session ID by scanning for live grip-session-*.sock files.

    Fallback when lock-file scan fails (e.g., session restarted with new ID
    but lock file not yet written). Matches sockets whose server PID file
    references a process that is a descendant of the current Claude Code
    process tree, or simply verifies the socket is connectable.

    This resolves GitHub issue #329: when the session-control-server restarts
    with a new session ID, the broadcast hook can now find the new socket.
    """
    import glob as _glob

    from _compat import grip_tmp_dir, grip_server_pid_path

    # Glob pattern differs on macOS (uses /tmp directly) vs others
    if sys.platform == "darwin":
        pattern = "/tmp/grip-session-*.sock"
    else:
        pattern = os.path.join(grip_tmp_dir(), "grip-session-*.sock")

    candidates = _glob.glob(pattern)
    if not candidates:
        return ""

    for sock_path in candidates:
        # Extract session ID from socket filename
        basename = os.path.basename(sock_path)
        # grip-session-{session_id}.sock
        if not basename.startswith("grip-session-") or not basename.endswith(".sock"):
            continue
        sid = basename[len("grip-session-"):-len(".sock")]
        if not sid:
            continue

        # Verify the server is alive (prevents connecting to orphaned sockets);
        # with no PID file, the socket must accept a connection instead
        pid_path = grip_server_pid_path(sid)
        if os.path.exists(pid_path):
            if not _server_alive(pid_path):
                continue
        elif not _socket_connectable(sock_path):
            continue

        return sid

    return ""


def _server_alive(pid_path: str) -> bool:
    """True while the control server whose PID file is ``pid_path`` still runs.

    The file holds bash's ``$!`` from ``hooks/session-start.sh`` or
    ``scripts/grip-pair.sh``. On Windows that is a Git Bash PID, which no Windows
    call can see, and ``os.kill(pid, 0)`` sends Ctrl+C to a console process group
    instead of checking anything, so Git's ``ps -W`` listing judges it there
    (GRIP#8883). A listing that cannot judge counts the server as gone, which only
    skips its socket.
    """
    try:
        with open(pid_path, "r") as f:
            server_pid = int(f.read().strip())
    except (ValueError, OSError):
        return False
    if sys.platform == "win32":
        try:
            from windows_processes import git_bash_pid_alive
        except ImportError:
            return False
        return git_bash_pid_alive(server_pid, when_unknown=False)
    try:
        os.kill(server_pid, 0)  # signal 0 = existence check
    except OSError:
        return False
    return True


def _socket_connectable(sock_path: str) -> bool:
    """True when the socket at ``sock_path`` accepts a connection."""
    if not _UNIX_SOCKETS_AVAILABLE:
        return False
    try:
        test_sock = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
        test_sock.settimeout(0.5)
        test_sock.connect(sock_path)
        test_sock.close()
    except Exception:
        return False
    return True


def discover_session_id() -> str:
    """Discover session ID by matching the Claude Code process PID to lock files.

    Uses process-tree matching to prevent cross-session contamination:
    only returns a session whose lock file 'pid' matches this hook's
    grandparent PID (the Claude Code node process).

    Falls back to socket-file glob when lock files don't match (issue #329:
    new session IDs after server restart).
    """
    claude_pid = _get_claude_code_pid()
    if not claude_pid:
        return ""

    # Per-process cache keyed by Claude Code PID (not global)
    from _compat import grip_tmp_dir
    cache_path = f"{grip_tmp_dir()}/grip-broadcast-{claude_pid}.session"
    try:
        if os.path.exists(cache_path):
            with open(cache_path, "r") as f:
                cached = f.read().strip()
            if cached and os.path.exists(grip_socket_path(cached)):
                return cached
    except OSError:
        pass

    # Scan lock files - only match sessions owned by THIS Claude Code process
    projects_dir = Path.home() / ".claude" / "projects"
    if not projects_dir.is_dir():
        # No projects dir — skip straight to socket glob fallback
        sid = _discover_from_socket_glob(claude_pid)
        if sid:
            _update_session_cache(cache_path, sid)
        return sid

    for lock_file in projects_dir.glob("*/grip/active-sessions/session-*.lock"):
        try:
            with open(lock_file) as f:
                data = json.load(f)
            sid = data.get("session_id", "")
            lock_pid = data.get("pid", 0)
            if sid and lock_pid == claude_pid and os.path.exists(grip_socket_path(sid)):
                _update_session_cache(cache_path, sid)
                return sid
        except (json.JSONDecodeError, OSError):
            continue

    # Fallback: glob for live sockets when lock-file scan found nothing.
    # This handles issue #329 — session restarted with a new ID, lock file
    # not yet updated, but the new socket is already listening.
    sid = _discover_from_socket_glob(claude_pid)
    if sid:
        _update_session_cache(cache_path, sid)
    return sid


def _update_session_cache(cache_path: str, session_id: str) -> None:
    """Write discovered session ID to per-process cache file."""
    try:
        with open(cache_path, "w") as f:
            f.write(session_id)
    except OSError:
        pass


def main():
    """Process PostToolUse hook input and broadcast high-impact events."""
    hook_input = parse_hook_input()
    if not hook_input:
        respond()
        return

    tool_name = hook_input.get("tool_name", "")

    # Only broadcast high-impact tools
    if tool_name not in HIGH_IMPACT_TOOLS:
        respond()
        return

    # Get session ID: hook input > environment > socket discovery
    session_id = (
        hook_input.get("session_id", "")
        or os.environ.get("CLAUDE_SESSION_ID", "")
    )

    # Check if this session ID has an active control server socket
    claude_id = session_id  # preserve Claude Code's own ID
    socket_path = grip_socket_path(session_id) if session_id else ""
    if not socket_path or not Path(socket_path).exists():
        # Fall back: find THIS process's session via PID-matched lock file
        fallback_id = discover_session_id()
        if fallback_id:
            session_id = fallback_id
            socket_path = grip_socket_path(fallback_id)
            # Write per-session mapping so context-gate-hook can find
            # the right injection file without the global cache
            if claude_id:
                try:
                    from _compat import grip_session_map_path
                    Path(grip_session_map_path(claude_id)).write_text(fallback_id)
                except OSError:
                    pass
        else:

            respond()
            return


    # Build event payload
    tool_input = hook_input.get("tool_input", {})
    tool_output = hook_input.get("tool_response", "")

    # Include per-instance UUID for multi-session steering isolation
    instance_uuid = _get_instance_uuid()

    event = {
        "type": "event",
        "event_type": tool_name,
        "data": sanitize_input(tool_input),
        "output_summary": sanitize_value(tool_output, MAX_OUTPUT_LENGTH),
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "claude_session_id": claude_id,
        "instance_uuid": instance_uuid,
    }

    # Broadcast (non-blocking, errors silently ignored)
    broadcast_event(socket_path, event)

    # Usage metrics tracking (Issue #117) - record skill invocations
    if tool_name == "Skill":
        _track_skill_usage(tool_input)

    respond()


def _track_skill_usage(tool_input: dict) -> None:
    """Record skill invocation to the centralized metrics pipeline.

    Delegates to lib/metrics_tracker.py (the single metrics facade) via
    a short-lived subprocess. Uses start_new_session=True so the child
    is reaped by init if this hook exits first, preventing zombie processes.

    Fire-and-forget is intentional: PostToolUse hooks must respond quickly
    (< 100ms) to avoid blocking Claude Code's tool pipeline.
    """
    skill_name = ""
    if isinstance(tool_input, dict):
        skill_name = tool_input.get("skill", "") or tool_input.get("name", "")
    if not skill_name:
        return
    tracker = Path(__file__).parent.parent / "lib" / "metrics_tracker.py"
    if not tracker.exists():
        return
    try:
        import subprocess as _sp
        _sp.Popen(
            [sys.executable, str(tracker), "record", "skill_invoked",
             f"skill={skill_name}"],
            stdout=_sp.DEVNULL, stderr=_sp.DEVNULL,
            start_new_session=True,
        )
    except OSError:
        pass


if __name__ == "__main__":
    main()
