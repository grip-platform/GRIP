"""PostToolUse hook: HOLISTIC.md fold guard (defence in depth).

Mirrors the OCF operational-context fold-guard. HOLISTIC.md is
machine-generated by lib/holistic_synthesiser.py, which is already
ledger-aware and bounded to a 40k target. This guard is a SAFETY NET: it
fires only on genuine runaway — a synthesiser regression or a manual edit —
NOT on the legitimate R1-ledger-exempt overflow the grounded council
ratified (the completeness ledger may push the kernel past the 40k target;
that is correct by design, not a fault). The ceiling is therefore the
runaway limit (2x target), not the target itself.

Async (never blocks the turn). Best-effort: any error -> silent allow.
The decision is the pure `evaluate()` function (Goodhart-testable without
stdin plumbing); `main()` is the thin hook I/O wrapper.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from hook_utils import parse_hook_input, respond, extract_tool_info  # noqa: E402

TARGET_FILE = "rules/HOLISTIC.md"
HOLISTIC_HARD_MAX = 80_000  # runaway ceiling; the 40k target is the synthesiser's job
GRIP_HOME = Path.home() / ".claude"


def evaluate(file_path: str, size: int) -> str | None:
    """Pure decision. Warning message iff the written file is the holistic
    kernel AND it exceeds the runaway ceiling; else None."""
    if TARGET_FILE not in str(file_path):
        return None
    if size <= HOLISTIC_HARD_MAX:
        return None
    return (
        f"[HOLISTIC-FOLD-GUARD] rules/HOLISTIC.md is {size:,} chars "
        f"(> {HOLISTIC_HARD_MAX:,} runaway ceiling). The kernel is "
        f"machine-generated and ledger-aware — this size indicates a "
        f"synthesiser regression or a manual edit, not the legitimate "
        f"R1-ledger overflow. Re-run: PYTHONPATH=$HOME/.claude "
        f"$HOME/.claude/venv/bin/python $HOME/.claude/lib/holistic_synthesiser.py"
    )


def main() -> None:
    hook_input = parse_hook_input()
    _, tool_input, _ = extract_tool_info(hook_input)
    file_path = tool_input.get("file_path", "")
    if TARGET_FILE not in str(file_path):
        respond()
        return
    try:
        size = len((GRIP_HOME / TARGET_FILE).read_text(encoding="utf-8"))
    except OSError:
        respond()
        return
    msg = evaluate(file_path, size)
    if msg:
        respond(msg)
    else:
        respond()


if __name__ == "__main__":
    main()
