#!/usr/bin/env python3
"""Insight propagator — writes insights to their canonical target files.

The final stage of the auto-insight pipeline:
1. insight_harvester.py — Extracts ★ Insight blocks
2. insight_classifier.py — Categorises per Rule 20
3. insight_router.py — Maps to target files
4. insight_propagator.py — THIS FILE — Actually writes

Design constraints:
- Atomic writes: either the propagation succeeds fully or not at all
- Dedup: never write the same insight twice (fingerprint check)
- Safe: creates parent directories, handles missing files gracefully
- Audit: logs all propagation actions to learning/propagation_log.jsonl
- Redirects: a lesson routed to a redirect stub lands in the skill it names

Usage:
    # As library
    from insight_propagator import propagate, propagate_batch

    # As CLI
    python3 lib/insight_propagator.py --dry-run  # See what would propagate
    python3 lib/insight_propagator.py            # Process pending insights
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import sys
from dataclasses import asdict, dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

CLAUDE_DIR = Path(os.environ.get("CLAUDE_DIR", Path.home() / ".claude"))
LIB_DIR = CLAUDE_DIR / "lib"
PROPAGATION_LOG = CLAUDE_DIR / "learning" / "propagation_log.jsonl"
PROPAGATION_STATE = CLAUDE_DIR / "state" / "propagation_fingerprints.json"

if str(LIB_DIR) not in sys.path:
    sys.path.insert(0, str(LIB_DIR))

from insight_classifier import ClassificationResult, InsightCategory, classify
from insight_router import PropagationTarget, RoutingResult, WriteMode, route


@dataclass
class PropagationResult:
    """Result of propagating a single insight."""
    success: bool
    category: str
    targets_written: List[str]
    targets_skipped: List[str]
    error: Optional[str] = None
    fingerprint: Optional[str] = None


def _fingerprint(content: str) -> str:
    """Generate a dedup fingerprint for content."""
    normalised = " ".join(content.lower().split())
    return hashlib.sha256(normalised.encode()).hexdigest()[:16]


def _load_fingerprints() -> set:
    """Load previously propagated fingerprints."""
    if not PROPAGATION_STATE.exists():
        return set()
    try:
        data = json.loads(PROPAGATION_STATE.read_text())
        return set(data.get("fingerprints", []))
    except (json.JSONDecodeError, OSError):
        return set()


def _save_fingerprints(fps: set) -> None:
    """Persist fingerprints to disk."""
    PROPAGATION_STATE.parent.mkdir(parents=True, exist_ok=True)
    PROPAGATION_STATE.write_text(json.dumps({
        "fingerprints": list(fps),
        "updated_at": datetime.now(timezone.utc).isoformat(),
    }, indent=2))


def _log_propagation(entry: Dict[str, Any]) -> None:
    """Append to propagation audit log."""
    PROPAGATION_LOG.parent.mkdir(parents=True, exist_ok=True)
    entry["timestamp"] = datetime.now(timezone.utc).isoformat()
    with open(PROPAGATION_LOG, "a") as f:
        f.write(json.dumps(entry) + "\n")


def _format_insight_entry(content: str, category: InsightCategory) -> str:
    """Format an insight for appending to a file."""
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    category_label = category.value.replace("_", " ").title()

    # Truncate very long insights
    if len(content) > 2000:
        content = content[:1997] + "..."

    return f"""
---

### [{category_label}] {timestamp}

{content.strip()}

"""


def _append_to_file(path: Path, content: str) -> bool:
    """Append content to a file, creating it if needed."""
    try:
        path.parent.mkdir(parents=True, exist_ok=True)

        # If file doesn't exist, create with header
        if not path.exists():
            header = f"# {path.stem.replace('_', ' ').title()}\n\n"
            header += f"Auto-generated by insight_propagator.py per Rule 20.\n\n"
            path.write_text(header)

        # Append the insight
        with open(path, "a") as f:
            f.write(content)

        return True
    except OSError:
        return False


def _append_to_section(path: Path, section: str, content: str) -> bool:
    """Append content to a specific section in a file.

    If the section doesn't exist, creates it at the end.
    """
    try:
        path.parent.mkdir(parents=True, exist_ok=True)

        if not path.exists():
            # Create file with section
            path.write_text(f"# {path.stem}\n\n{section}\n\n{content}")
            return True

        text = path.read_text()

        # Find section
        section_pattern = f"\n{section}\n"
        if section_pattern in text:
            # Insert after section header
            idx = text.index(section_pattern) + len(section_pattern)
            new_text = text[:idx] + content + text[idx:]
        else:
            # Append section at end
            new_text = text.rstrip() + f"\n\n{section}\n\n{content}"

        path.write_text(new_text)
        return True
    except OSError:
        return False


_FRONTMATTER_RE = re.compile(r"\A---\n(.*?)\n---\n", re.DOTALL)
_REDIRECT_RE = re.compile(r"^redirect_to:\s*([\w-]+)\s*$", re.MULTILINE)


def _follow_skill_redirect(path: Path) -> Path:
    """Return the skill a redirect stub points at, or ``path`` unchanged.

    skills/shipit/SKILL.md is a thin redirect (``redirect_to: auto``) with a
    test keeping it under 1500 bytes; one lesson appended to it grew it past
    that. A lesson belongs with the skill the stub hands over to. Followed
    once, so a redirect to another redirect cannot loop.
    """
    if path.name != "SKILL.md":
        return path
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return path
    frontmatter = _FRONTMATTER_RE.match(text)
    redirect = frontmatter and _REDIRECT_RE.search(frontmatter.group(1))
    if not redirect:
        return path
    target = path.parent.parent / redirect.group(1) / "SKILL.md"
    return target if target.is_file() else path


def _write_target(path: Path, target: PropagationTarget, formatted: str) -> bool:
    """Write one formatted insight to ``path`` in ``target``'s write mode."""
    if target.write_mode == WriteMode.APPEND_SECTION:
        return _append_to_section(path, target.section or "## Notes", formatted)
    if target.write_mode in (WriteMode.APPEND, WriteMode.CREATE_NEW):
        return _append_to_file(path, formatted)
    return False


def _write_targets(
    targets: List[PropagationTarget],
    formatted: str,
) -> tuple[List[str], List[str]]:
    """Write to every target; return the paths written and the reasons skipped.

    Two targets that resolve to the same file, such as a redirect stub and the
    skill it names, are written once.
    """
    written: List[str] = []
    skipped: List[str] = []
    for target in targets:
        # Check if target path exists (for skill files, skip if skill doesn't exist)
        if "skills/" in str(target.path) and not target.path.parent.exists():
            skipped.append(f"skill_not_found:{target.path.parent.name}")
            continue
        path = _follow_skill_redirect(target.path)
        if str(path) in written:
            skipped.append(f"duplicate_target:{path}")
            continue
        if _write_target(path, target, formatted):
            written.append(str(path))
        else:
            skipped.append(f"write_failed:{path}")
    return written, skipped


def propagate(
    content: str,
    classification: Optional[ClassificationResult] = None,
    routing: Optional[RoutingResult] = None,
    dry_run: bool = False,
) -> PropagationResult:
    """Propagate a single insight to its target files.

    Args:
        content: The insight text.
        classification: Pre-computed classification (or will be computed).
        routing: Pre-computed routing (or will be computed).
        dry_run: If True, don't actually write files.

    Returns:
        PropagationResult with success status and details.
    """
    # Dedup check
    fp = _fingerprint(content)
    existing_fps = _load_fingerprints()
    if fp in existing_fps:
        return PropagationResult(
            success=True,
            category="skipped",
            targets_written=[],
            targets_skipped=["already_propagated"],
            fingerprint=fp,
        )

    # Classify if not provided
    if classification is None:
        classification = classify(content)

    # Route if not provided
    if routing is None:
        routing = route(classification, content)

    # Skip if no propagation needed
    if routing.skip_reason:
        return PropagationResult(
            success=True,
            category=classification.category.value,
            targets_written=[],
            targets_skipped=[routing.skip_reason],
            fingerprint=fp,
        )

    # Propagate to each target
    formatted = _format_insight_entry(content, classification.category)
    if dry_run:
        # Report where each lesson would really land, as _write_targets writes
        # it: redirects followed, and a file reached twice listed once.
        resolved = dict.fromkeys(str(_follow_skill_redirect(t.path)) for t in routing.targets)
        targets_written = [f"[DRY RUN] {path}" for path in resolved]
        targets_skipped: List[str] = []
    else:
        targets_written, targets_skipped = _write_targets(routing.targets, formatted)

    # Update fingerprints
    if not dry_run and targets_written:
        existing_fps.add(fp)
        _save_fingerprints(existing_fps)

    # Log the propagation
    _log_propagation({
        "fingerprint": fp,
        "category": classification.category.value,
        "signals": classification.signals,
        "targets_written": targets_written,
        "targets_skipped": targets_skipped,
        "dry_run": dry_run,
    })

    return PropagationResult(
        success=len(targets_written) > 0 or len(routing.targets) == 0,
        category=classification.category.value,
        targets_written=targets_written,
        targets_skipped=targets_skipped,
        fingerprint=fp,
    )


def propagate_batch(
    contents: List[str],
    dry_run: bool = False,
) -> List[PropagationResult]:
    """Propagate multiple insights."""
    return [propagate(c, dry_run=dry_run) for c in contents]


def _tally_line(
    line: str,
    existing_fps: set,
    results: Dict[str, Any],
    dry_run: bool,
) -> None:
    """Propagate one insights.jsonl line and count its outcome into ``results``."""
    try:
        content = json.loads(line).get("text", "")
        if not content:
            return

        # Quick dedup check before full processing
        if _fingerprint(content) in existing_fps:
            results["skipped_dedup"] += 1
            return

        result = propagate(content, dry_run=dry_run)
        results["processed"] += 1

        if result.targets_written:
            results["propagated"] += 1
        elif "conversation_only" in result.category:
            results["skipped_category"] += 1

        results["details"].append({
            "fingerprint": result.fingerprint,
            "category": result.category,
            "written": len(result.targets_written),
        })

    except (json.JSONDecodeError, KeyError):
        results["errors"] += 1


def process_pending_insights(dry_run: bool = False) -> Dict[str, Any]:
    """Process all insights from insights.jsonl that haven't been propagated.

    Returns:
        Summary dict with counts and details.
    """
    insights_file = CLAUDE_DIR / "learning" / "insights.jsonl"
    if not insights_file.exists():
        return {"processed": 0, "error": "insights.jsonl not found"}

    existing_fps = _load_fingerprints()
    results = {
        "processed": 0,
        "propagated": 0,
        "skipped_dedup": 0,
        "skipped_category": 0,
        "errors": 0,
        "dry_run": dry_run,
        "details": [],
    }

    with open(insights_file) as f:
        for line in f:
            _tally_line(line, existing_fps, results, dry_run)

    return results


def main() -> None:
    """CLI entry point."""
    import argparse

    parser = argparse.ArgumentParser(description="GRIP Insight Propagator")
    parser.add_argument("--dry-run", action="store_true", help="Don't write files")
    parser.add_argument("--json", action="store_true", help="JSON output")
    parser.add_argument("--content", type=str, help="Single insight to propagate")

    args = parser.parse_args()

    if args.content:
        # Single insight mode
        result = propagate(args.content, dry_run=args.dry_run)
        if args.json:
            print(json.dumps(asdict(result), indent=2))
        else:
            status = "✓" if result.success else "✗"
            print(f"{status} [{result.category}] → {len(result.targets_written)} targets")
            for t in result.targets_written:
                print(f"  + {t}")
            for s in result.targets_skipped:
                print(f"  - {s}")
    else:
        # Batch mode: process pending insights
        results = process_pending_insights(dry_run=args.dry_run)
        if args.json:
            print(json.dumps(results, indent=2))
        else:
            prefix = "[DRY RUN] " if args.dry_run else ""
            print(f"{prefix}Insight Propagator Summary:")
            print(f"  Processed: {results['processed']}")
            print(f"  Propagated: {results['propagated']}")
            print(f"  Skipped (dedup): {results['skipped_dedup']}")
            print(f"  Skipped (conversation): {results['skipped_category']}")
            print(f"  Errors: {results['errors']}")


if __name__ == "__main__":
    main()
