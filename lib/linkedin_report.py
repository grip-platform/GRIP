"""LinkedIn Feed Scout — Markdown report writer.

Takes a list of (CombinedScore, Draft) tuples and writes a Markdown
report V>> reads inline. Designed for V>>'s "Tier-1 attended" workflow:
one report per run, per-post block with score breakdown + draft + a
clickable "Open in Brave" CTA.

Pure function: no I/O beyond the single file write. Tests can build
fixture data and assert on the rendered Markdown.
"""

from __future__ import annotations

import datetime
from dataclasses import dataclass
from pathlib import Path

from linkedin_drafter import Draft
from linkedin_scorer import CombinedScore


@dataclass
class ReportContext:
    """Metadata header for the report (telemetry from extract_feed)."""

    run_started_at: str  # ISO 8601
    run_finished_at: str  # ISO 8601
    posts_seen: int  # raw_extracted from telemetry
    posts_new: int  # deduplicated from telemetry
    posts_ranked: int  # how many made it into the top-K
    errors: list[str]  # any extraction errors
    mode: str = "attended"  # "attended" (Tier-1) or "stealth" (Tier-2)


def render_report(
    ctx: ReportContext,
    pairs: list[tuple[CombinedScore, Draft]],
) -> str:
    """Render the full Markdown report for one run."""
    sections = [_render_header(ctx)]
    if not pairs:
        sections.append("_No posts cleared the scoring threshold this run._\n")
    else:
        for rank_idx, (score, draft) in enumerate(pairs, start=1):
            sections.append(_render_post_block(rank_idx, score, draft))
    sections.append(_render_footer())
    return "\n\n".join(sections)


def _render_header(ctx: ReportContext) -> str:
    err_line = ""
    if ctx.errors:
        err_line = f"\n- Extraction errors: {len(ctx.errors)} (see telemetry)"
    return (
        f"# LinkedIn Feed Scout — {ctx.run_started_at}\n\n"
        f"Mode: **{ctx.mode}** (Tier-1 = CDP attach to your Brave)\n\n"
        f"- Run window: {ctx.run_started_at} → {ctx.run_finished_at}\n"
        f"- Posts seen in feed: {ctx.posts_seen}\n"
        f"- New posts (after dedup): {ctx.posts_new}\n"
        f"- Top-K ranked + drafted: {ctx.posts_ranked}"
        f"{err_line}\n\n"
        f"Review each draft below, edit as needed, then click the post URL "
        f"to open in Brave and paste your chosen comment manually."
    )


def _render_post_block(rank_idx: int, score: CombinedScore, draft: Draft) -> str:
    post = score.post
    l1 = score.l1
    excerpt = (post.body_text or "")[:400].replace("\n", " ").strip()
    if len(post.body_text or "") > 400:
        excerpt += "…"

    hooks_line = _format_hooks_line(l1)
    boost_line = (
        f"\n- **Author boost** for: {', '.join(l1.author_matches)}"
        if l1.author_matches
        else ""
    )
    banned_line = (
        f"\n- **Banned-phrase scrubs applied**: {', '.join(draft.banned_hits)}"
        if draft.banned_hits
        else ""
    )
    error_line = (
        f"\n- **⚠ draft source**: {draft.source} ({draft.rationale})"
        if draft.source != "hal"
        else ""
    )

    return (
        f"---\n\n"
        f"## #{rank_idx}. {post.author_display}\n\n"
        f"_{post.author_headline}_\n\n"
        f"**Score**: final={score.final:.1f}, L1={l1.floor:.1f}, "
        f"L2 delta={score.l2.delta:.1f}{boost_line}\n"
        f"- **Rationale**: {draft.rationale}\n"
        f"- **Hooks fired**: {hooks_line}{banned_line}{error_line}\n\n"
        f"**Post excerpt**:\n\n> {excerpt}\n\n"
        f"**Open**: <{post.url}>\n\n"
        f"**Draft comment** ({draft.char_count} chars):\n\n"
        f"```\n{draft.comment_text}\n```"
    )


def _format_hooks_line(l1) -> str:
    parts = []
    if l1.tier_1_hits:
        parts.append(f"T1: {', '.join(h.phrase for h in l1.tier_1_hits[:5])}")
    if l1.tier_2_hits:
        parts.append(f"T2: {', '.join(h.phrase for h in l1.tier_2_hits[:5])}")
    if l1.tier_3_hits:
        parts.append(f"T3: {', '.join(h.phrase for h in l1.tier_3_hits[:3])}")
    return " · ".join(parts) if parts else "(no hooks — author-boost only)"


def _render_footer() -> str:
    return (
        "---\n\n"
        "**After publishing a comment**: run `linkedin-feed-scout"
        " --mark-commented <post-id-prefix>` or edit "
        "`state/linkedin/commented.jsonl` directly to prevent re-surfacing.\n\n"
        "**Skipping a post**: use `--mark-skipped <post-id-prefix>` so the"
        " H-LINKEDIN-SCOUT-1 precision hypothesis can verify against your"
        " comment/skip ledger.\n\n"
        "Generated by `bin/linkedin-feed-scout` — see "
        "`plans/log-into-linkedin-with-polished-flurry.md` for the design."
    )


def write_report(
    report_dir: Path,
    ctx: ReportContext,
    pairs: list[tuple[CombinedScore, Draft]],
) -> Path:
    """Render + write report.md to report_dir/<date>/report.md."""
    date_str = datetime.datetime.now(datetime.UTC).strftime("%Y-%m-%d")
    out_dir = report_dir / date_str
    out_dir.mkdir(parents=True, exist_ok=True)

    ts_str = datetime.datetime.now(datetime.UTC).strftime("%H-%M-%SZ")
    out_path = out_dir / f"report-{ts_str}.md"

    out_path.write_text(render_report(ctx, pairs), encoding="utf-8")
    return out_path


__all__ = ["ReportContext", "render_report", "write_report"]
