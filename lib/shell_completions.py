#!/usr/bin/env python3
"""Shell completion generator for GRIP commands and modes.

Generates zsh and bash completion scripts from the skill registry
and mode definitions.

Usage:
    python3 lib/shell_completions.py zsh     # Output zsh completion script
    python3 lib/shell_completions.py bash    # Output bash completion script
    python3 lib/shell_completions.py list    # List all completable commands
"""

import sys
from pathlib import Path

CLAUDE_DIR = Path(__file__).parent.parent
SKILLS_DIR = CLAUDE_DIR / "skills"
MODES_DIR = CLAUDE_DIR / "modes" / "definitions"


def get_commands() -> list[str]:
    """Get all GRIP slash commands from skill directories."""
    commands = []
    if not SKILLS_DIR.exists():
        return commands
    for skill_dir in sorted(SKILLS_DIR.iterdir()):
        if not skill_dir.is_dir():
            continue
        if (skill_dir / "SKILL.md").exists() or (skill_dir / "SKILL.grip").exists():
            commands.append(skill_dir.name)
    return commands


def get_modes() -> list[str]:
    """Get all mode names from mode definitions."""
    modes = []
    if not MODES_DIR.exists():
        return modes
    for mode_file in sorted(MODES_DIR.glob("*.yaml")):
        mode_name = mode_file.stem.replace("-mode", "")
        modes.append(mode_name)
    return modes


def generate_zsh() -> str:
    """Generate zsh completion script."""
    commands = get_commands()
    modes = get_modes()

    cmd_list = " ".join(commands)
    mode_list = " ".join(modes)

    return f"""# GRIP zsh completions — generated by shell_completions.py
# Add to .zshrc: eval "$(python3 ~/.claude/lib/shell_completions.py zsh)"

_grip_commands=({cmd_list})
_grip_modes=({mode_list})

_grip_slash_complete() {{
    local -a completions
    local prefix="${{words[CURRENT]}}"

    # Complete /command names
    if [[ "$prefix" == /* ]]; then
        local stripped="${{prefix#/}}"
        completions=(${{_grip_commands[@]/#/\\/}})
        _describe 'grip command' completions
        return
    fi
}}

_grip_mode_complete() {{
    local -a completions
    completions=($_grip_modes)
    _describe 'grip mode' completions
}}

# Register completions
compdef _grip_slash_complete grip
compdef '_arguments "1:mode:_grip_mode_complete"' grip-mode
"""


def generate_bash() -> str:
    """Generate bash completion script."""
    commands = get_commands()
    modes = get_modes()

    cmd_list = " ".join(commands)
    mode_list = " ".join(modes)

    return f"""# GRIP bash completions — generated by shell_completions.py
# Add to .bashrc: eval "$(python3 ~/.claude/lib/shell_completions.py bash)"

_grip_complete() {{
    local cur="${{COMP_WORDS[COMP_CWORD]}}"
    local commands="{cmd_list}"
    local modes="{mode_list}"

    if [[ "$cur" == /* ]]; then
        local stripped="${{cur#/}}"
        COMPREPLY=($(compgen -W "${{commands// / /}}" -- "$cur"))
    else
        COMPREPLY=($(compgen -W "$commands $modes" -- "$cur"))
    fi
}}

complete -F _grip_complete grip
"""


def main() -> None:
    if len(sys.argv) < 2:
        print("Usage: shell_completions.py <zsh|bash|list>")
        sys.exit(1)

    cmd = sys.argv[1]

    if cmd == "zsh":
        print(generate_zsh())
    elif cmd == "bash":
        print(generate_bash())
    elif cmd == "list":
        commands = get_commands()
        modes = get_modes()
        print(f"Commands ({len(commands)}):")
        for c in commands:
            print(f"  /{c}")
        print(f"\nModes ({len(modes)}):")
        for m in modes:
            print(f"  {m}")
    else:
        print(f"Unknown: {cmd}")
        sys.exit(1)


if __name__ == "__main__":
    main()
