#!/usr/bin/env bash
# polyglot.sh -- GRIP Polyglot Document Utility
# This file is itself a polyglot: valid bash AND valid markdown.
# Run: ./polyglot.sh --verify | --wrap <file> | --hash <file> | --check <file>
# Read: open polyglot.sh in any markdown viewer

: '
# GRIP Polyglot Document Library

## Purpose

Utility for creating and verifying polyglot documents -- files that are
simultaneously valid markdown AND valid bash, with self-verification
and content-addressing (SHA256 hash = identity).

## Architecture

A polyglot document has two zones:

```
HUMAN ZONE  (inside : '"'"' ... '"'"' heredoc)  -- markdown, rules, intent
AI ZONE     (outside heredoc)                    -- executable verification
```

The human zone is invisible to bash (heredoc comment).
The AI zone is invisible to casual markdown readers (looks like code).
The hash unifies both zones under one identity.

## Commands

| Command | Description |
|---------|-------------|
| `--verify` | Verify this library is itself a valid polyglot |
| `--wrap <file.md>` | Wrap a markdown file into a polyglot document |
| `--hash <file>` | Output SHA256 hash of a polyglot document |
| `--check <file>` | Check if a file is a valid polyglot |
| `--strip <file>` | Extract the markdown (human zone) from a polyglot |

## Heredoc Technique

The `: '"'"'` bash builtin is a no-op. Combined with single-quote heredoc,
it creates an invisible comment block where markdown lives safely.
Single quotes inside the markdown must be escaped or avoided.

## Self-Identical Property

This library is a polyglot document created by the polyglot library.
`polyglot.sh --verify` proves this. The tool and the spec are one.
'

# === POLYGLOT LIBRARY: Executable Zone ===

set -euo pipefail

POLYGLOT_VERSION="1.0.0"
SELF="$(cd "$(dirname "$0")" && pwd)/$(basename "$0")"

# --- Core Functions ---

polyglot_hash() {
    local file="${1:?Usage: polyglot_hash <file>}"
    shasum -a 256 -- "$file" | cut -d' ' -f1
}

polyglot_is_valid() {
    local file="${1:?Usage: polyglot_is_valid <file>}"
    local has_shebang has_heredoc_open has_heredoc_close has_markdown has_bash

    has_shebang=$(head -1 "$file" | grep -c "^#!/" 2>/dev/null || true)
    has_heredoc_open=$(grep -c "^: '" "$file" 2>/dev/null || true)
    has_heredoc_close=$(grep -c "^'" "$file" 2>/dev/null || true)
    has_markdown=$(grep -c "^#\|^##\|^-\|^|" "$file" 2>/dev/null || true)
    has_bash=$(grep -c "^[a-zA-Z_]*=\|^echo\|^if \|^fi$\|^function " "$file" 2>/dev/null || true)

    if [ "$has_shebang" -gt 0 ] && [ "$has_heredoc_open" -gt 0 ] && \
       [ "$has_heredoc_close" -gt 0 ] && [ "$has_markdown" -gt 0 ] && \
       [ "$has_bash" -gt 0 ]; then
        return 0
    else
        return 1
    fi
}

polyglot_check() {
    local file="${1:?Usage: polyglot_check <file>}"

    echo "=== Polyglot Check: $(basename "$file") ==="
    echo "Hash: $(polyglot_hash "$file")"

    if polyglot_is_valid "$file"; then
        echo "Status: VALID polyglot (md+bash)"

        local md_lines bash_lines total_lines
        total_lines=$(wc -l < "$file" | tr -d ' ')
        # Count lines inside heredoc as markdown
        md_lines=$(sed -n "/^: '/,/^'/p" "$file" | wc -l | tr -d ' ')
        bash_lines=$((total_lines - md_lines))

        echo "Total lines: ${total_lines}"
        echo "Human zone (md): ${md_lines} lines"
        echo "AI zone (bash): ${bash_lines} lines"
        return 0
    else
        echo "Status: NOT a valid polyglot"
        return 1
    fi
}

polyglot_strip() {
    local file="${1:?Usage: polyglot_strip <file>}"
    # Extract content between : ' and closing '
    sed -n "/^: '/,/^'/{/^: '/d;/^'/d;p;}" "$file"
}

polyglot_wrap() {
    local input="${1:?Usage: polyglot_wrap <input.md> [output.md]}"
    local output="${2:-${input}}"
    local tmp_file

    if [ ! -f "$input" ]; then
        echo "Error: file not found: $input" >&2
        return 1
    fi

    # Check for unescaped single quotes in content (breaks heredoc)
    if grep -q "'" "$input" 2>/dev/null; then
        echo "Warning: input contains single quotes. They will be preserved but" >&2
        echo "may cause issues in the heredoc. Consider using smart quotes." >&2
    fi

    tmp_file=$(mktemp)

    {
        echo '#!/usr/bin/env bash'
        echo '# Polyglot document: valid markdown + valid bash'
        echo "# Generated by GRIP polyglot.sh v${POLYGLOT_VERSION}"
        echo "# Hash at generation: (computed after write)"
        echo ''
        echo ": '"
        cat "$input"
        echo "'"
        echo ''
        echo '# === Self-Verification ==='
        echo 'SELF_HASH=$(shasum -a 256 "$0" | cut -d'"'"' '"'"' -f1)'
        echo 'echo "Document: $(basename $0)"'
        echo 'echo "Hash: ${SELF_HASH}"'
        echo ''
        echo 'POLYGLOT_LIB="${BASH_SOURCE[0]%/*}/polyglot.sh"'
        echo 'if [ -f "$POLYGLOT_LIB" ]; then'
        echo '    source "$POLYGLOT_LIB"'
        echo '    polyglot_check "$0"'
        echo 'else'
        echo '    echo "Self-check: standalone mode (polyglot.sh not found)"'
        echo '    echo "Polyglot: yes (this file executed as bash)"'
        echo 'fi'
    } > "$tmp_file"

    # Compute hash and update the header
    local hash
    hash=$(shasum -a 256 "$tmp_file" | cut -d' ' -f1)
    sed -i.bak "s/Hash at generation: (computed after write)/Hash at generation: ${hash}/" "$tmp_file"
    rm -f "${tmp_file}.bak"

    mv "$tmp_file" "$output"
    chmod +x "$output"
    echo "Wrapped: $output (polyglot, $(wc -l < "$output" | tr -d ' ') lines)"
}

polyglot_verify_self() {
    echo "=== Self-Verification: polyglot.sh v${POLYGLOT_VERSION} ==="
    echo "Path: ${SELF}"
    echo "Hash: $(polyglot_hash "$SELF")"

    if polyglot_is_valid "$SELF"; then
        echo "Self-check: PASS -- this library IS a polyglot document"
        echo "The tool and the spec are one."
        return 0
    else
        echo "Self-check: FAIL -- library lost its polyglot property"
        return 1
    fi
}

# --- CLI Dispatch ---

if [ "${BASH_SOURCE[0]}" = "$0" ]; then
    # Running directly (not sourced)
    case "${1:-}" in
        --verify)
            polyglot_verify_self
            ;;
        --wrap)
            polyglot_wrap "${2:-}" "${3:-}"
            ;;
        --hash)
            polyglot_hash "${2:?Usage: polyglot.sh --hash <file>}"
            ;;
        --check)
            polyglot_check "${2:?Usage: polyglot.sh --check <file>}"
            ;;
        --strip)
            polyglot_strip "${2:?Usage: polyglot.sh --strip <file>}"
            ;;
        --version)
            echo "polyglot.sh v${POLYGLOT_VERSION}"
            ;;
        *)
            echo "GRIP Polyglot Document Utility v${POLYGLOT_VERSION}"
            echo ""
            echo "Usage: polyglot.sh <command> [args]"
            echo ""
            echo "Commands:"
            echo "  --verify         Verify this library is a valid polyglot"
            echo "  --wrap <file>    Wrap markdown into a polyglot document"
            echo "  --hash <file>    Output SHA256 hash"
            echo "  --check <file>   Check if file is a valid polyglot"
            echo "  --strip <file>   Extract markdown from polyglot"
            echo "  --version        Show version"
            ;;
    esac
fi
