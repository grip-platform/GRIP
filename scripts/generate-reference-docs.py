#!/usr/bin/env python3
"""
Generate docs/COMMANDS.md and docs/AGENTS.md from the filesystem.

These two reference docs drifted badly because nothing regenerated them
(COMMANDS header said 53 / body under-listed; AGENTS said 16). This script
makes them reproducible: counts and entries come straight from the files on
disk, so the header count can never disagree with the body again.

They are plain Markdown tables (renamed from a bespoke ``.grip`` DSL that no
renderer understood) so they render on GitHub and highlight in editors.

Single-source-of-truth alignment: counts come from lib/asset_counter.py's
``count_inventory()`` (the same counter scripts/grip-stats.sh and the
doc-drift hook use, unified in PR #3285). The generator enumerates EXACTLY the
globs that counter uses, so the docs can never diverge from the canonical count:

  agents    asset_counter.AGENT_GLOB (agents/**/*.md, subfolders included, as
                         Claude Code loads them) minus NON_AGENT_FILES (CLAUDE.md
                         and _base-protocol.md)
  commands  commands/*.md minus CLAUDE.md

Each render asserts its row count equals count_inventory(), so a drift between
this generator and the canonical counter fails loudly rather than silently.
The agents render also asserts each tier's rows equal count_agents_by_tier(),
and every tier comes from the counter's own reader, asset_counter.agent_tier.

Honesty (R0): the old budget/savings columns were hand estimates with no
measurement behind them, so they are dropped rather than fabricated. Only
fields that exist in the files are emitted (command description; agent
name/model/tier/description from frontmatter).

Usage:
    python3 ~/.claude/scripts/generate-reference-docs.py            # write files
    python3 ~/.claude/scripts/generate-reference-docs.py --check    # diff only, exit 1 if stale
    python3 ~/.claude/scripts/generate-reference-docs.py --stdout   # print, don't write
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

_LIB = Path(__file__).resolve().parent.parent / "lib"
if str(_LIB) not in sys.path:
    sys.path.insert(0, str(_LIB))
from asset_counter import (  # noqa: E402
    AGENT_GLOB,
    NON_AGENT_FILES,
    TIER_ORDER,
    agent_tier,
    count_agents_by_tier,
    count_inventory,
    refresh_readme_markers,
)
from claude_dir import get_claude_dir  # noqa: E402

GRIP_DIR = get_claude_dir()
def _version_from_claude_md() -> str:
    """Read the framework version from the CLAUDE.md header — the stated source.

    This used to be the literal "6.0.0" under a comment reading "tracks GRIP
    framework major (CLAUDE.md header)". The comment was false: the header said
    9.0.0 and had since 2026-08-06 (CHANGELOG "[9.0.0] - The Estate Release"),
    so every generated doc was stamped with a version four majors stale, and
    AGENTS.md — the cross-tool contract other harnesses read — announced 6.0.0
    while CLAUDE.md announced 9.0.0.

    Deriving it removes the second copy rather than correcting it. Fails LOUD:
    a generator that silently stamps a guessed version is how this drift began.
    """
    # `lines[0]` on an EMPTY CLAUDE.md raises IndexError before the check below
    # can fire, masking "no version marker" behind a bare traceback (AGORA #4848).
    lines = (GRIP_DIR / "CLAUDE.md").read_text(encoding="utf-8").splitlines()
    header = lines[0] if lines else ""
    match = re.match(r"#\s*GRIP\s+v(\d+\.\d+\.\d+)", header.strip())
    if not match:
        raise SystemExit(
            f"cannot read the GRIP version from the CLAUDE.md header: {header!r}. "
            "Expected '# GRIP vX.Y.Z'. Fix the header rather than hardcoding a version here."
        )
    return match.group(1)


# NOT called at import (AGORA #4848). Module-level filesystem I/O crashes any
# importer - a linter, an IDE indexer, another build script - on a partially
# checked-out tree, and does it before argparse can print anything useful. The
# value is resolved once, lazily, at the point of use.
_VERSION_CACHE: list[str] = []


def grip_version() -> str:
    """The framework version, read once from the CLAUDE.md header on first use."""
    if not _VERSION_CACHE:
        _VERSION_CACHE.append(_version_from_claude_md())
    return _VERSION_CACHE[0]
_AUTOGEN = (
    "> Auto-generated by `scripts/generate-reference-docs.py` -- do not hand-edit.\n"
    "> Run the script (or `/update-docs`) to refresh."
)

_DESC_LABEL_RE = re.compile(r"^\*{0,2}(?:Description|Desc|Summary)\*{0,2}\s*:\s*(.+)$", re.I)
_NOISE_RES = (
    re.compile(r"^[-*]\s"),  # list bullet
    re.compile(r"^\d+\.\s"),  # numbered list
    re.compile(r"^\*{2}[^*]+\*{2}\s*:?\s*$"),  # bold label line, no value
    re.compile(r"^-{3,}$"),  # horizontal rule
    re.compile(r"^~?\d+\s*(?:T\b|tokens?\b)", re.I),  # budget annotation, not a description
)


def _read_frontmatter(text: str) -> dict[str, str]:
    """Parse a simple `---` YAML frontmatter block into a flat str->str dict.

    Only single-line `key: value` pairs are captured (all we need). Returns {}
    when the file has no frontmatter.
    """
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    if end == -1:
        return {}
    out: dict[str, str] = {}
    for line in text[3:end].splitlines():
        m = re.match(r"^([A-Za-z0-9_-]+):\s*(.*)$", line)
        if not m:
            continue
        key, val = m.group(1).strip(), m.group(2).strip()
        if val and val[0] in "\"'" and val[-1:] == val[0]:
            val = val[1:-1]
        out[key] = val
    return out


def _body_after_frontmatter(text: str) -> str:
    if text.startswith("---"):
        end = text.find("\n---", 3)
        if end != -1:
            nl = text.find("\n", end + 1)
            return text[nl + 1 :] if nl != -1 else ""
    return text


def _clean(desc: str, limit: int = 120) -> str:
    """Collapse whitespace, protect the `|` delimiter, trim to one sentence/limit."""
    desc = re.sub(r"\s+", " ", desc).strip().replace("|", "/")
    desc = desc.lstrip("#").strip().strip("*").strip()
    if not desc:
        return ""
    sentence = re.split(r"(?<=[.!?])\s", desc, maxsplit=1)[0]
    chosen = sentence if len(sentence) <= limit else desc[:limit].rsplit(" ", 1)[0]
    chosen = chosen.rstrip(" .")
    if len(chosen) < len(desc.rstrip(" .")):
        chosen += "…"
    return chosen


def _is_prose(s: str) -> bool:
    """True when a stripped line is usable description prose (not markdown chrome)."""
    if not s or s.startswith(("#", ";", ">", "|", "<!--", "===")):
        return False
    return not any(r.match(s) for r in _NOISE_RES)


def _extract_description(text: str) -> str:
    """Best-effort one-line description for a command/agent markdown file.

    Order: frontmatter `description:` -> an explicit `**Description**:` label ->
    first prose paragraph (fenced code skipped) -> the H1 heading. Shared by
    commands and agents so both handle frontmatter-less files (e.g. an agent
    base protocol) identically.
    """
    fm = _read_frontmatter(text)
    if fm.get("description"):
        return _clean(fm["description"])

    paragraph: list[str] = []
    in_fence = False
    for line in _body_after_frontmatter(text).splitlines():
        s = line.strip()
        if s.startswith("```"):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        label = _DESC_LABEL_RE.match(s)
        if label:  # an explicit "**Description**: ..." label wins outright
            return _clean(label.group(1).strip("*` "))
        if not _is_prose(s):
            if paragraph:
                break
            continue
        paragraph.append(s)
        if s.endswith((".", "!", "?")):
            break
    if paragraph:
        return _clean(" ".join(paragraph))
    for line in _body_after_frontmatter(text).splitlines():
        if line.startswith("# "):
            h = re.sub(r"^/\S+\s*", "", line[2:].strip())
            h = re.sub(r"\s*Command$", "", h, flags=re.I).strip()
            return _clean(h) if h else "(no description)"
    return "(no description)"


def collect_commands() -> list[tuple[str, str]]:
    """Every commands/*.md (minus CLAUDE.md), matching count_inventory's glob.

    A broken/foreign symlink still counts (the glob matches it) but cannot be
    read, so it gets an honest placeholder rather than being silently dropped —
    keeping the row count equal to the canonical command count.
    """
    rows: list[tuple[str, str]] = []
    for f in sorted((GRIP_DIR / "commands").glob("*.md")):
        if f.name == "CLAUDE.md":
            continue
        if not f.exists():  # broken symlink (e.g. an org-specific link to another machine)
            rows.append((f.stem, "(unresolved symlink -- target outside this checkout)"))
            continue
        rows.append((f.stem, _extract_description(f.read_text(encoding="utf-8", errors="ignore"))))
    return rows


def collect_agents() -> list[tuple[str, str, str, str]]:
    """Every agent file minus NON_AGENT_FILES, with count_inventory's AGENT_GLOB."""
    rows: list[tuple[str, str, str, str]] = []
    for f in sorted((GRIP_DIR / "agents").glob(AGENT_GLOB)):
        if f.name in NON_AGENT_FILES:
            continue
        text = f.read_text(encoding="utf-8", errors="ignore")
        fm = _read_frontmatter(text)
        name = fm.get("name") or f.stem
        model = fm.get("model") or "-"
        rows.append((name, model, agent_tier(text), _extract_description(text)))
    return rows


def render_commands(rows: list[tuple[str, str]]) -> str:
    # Count the SAME tree the rows were collected from. This used to be a
    # no-arg count_inventory(), which re-resolves get_claude_dir() at call
    # time — so the header count could come from a different tree than the
    # body. Under pytest that is not hypothetical: tests/conftest.py points
    # CLAUDE_DIR at an empty hermetic dir per test, so the no-arg count
    # returned 0 and this assert fired on a perfectly fresh doc.
    canonical = count_inventory(GRIP_DIR)["commands"]
    assert len(rows) == canonical, f"command rows {len(rows)} != count_inventory {canonical}"
    out = [
        "# GRIP Commands",
        "",
        _AUTOGEN,
        "",
        f"**{len(rows)} commands** — one row per `commands/*.md` "
        "(count from `lib/asset_counter.py` `count_inventory()`). "
        "Budget/savings columns were dropped: hand estimates, never measured (R0).",
        "",
        "| Command | Description |",
        "| --- | --- |",
    ]
    out += [f"| `/{name}` | {desc} |" for name, desc in rows]
    out += ["", f"<!-- generated: {len(rows)} commands · v{grip_version()} · source commands/*.md -->", ""]
    return "\n".join(out)


def _agent_table(group: list[tuple[str, str, str, str]]) -> list[str]:
    """Markdown table for one tier's agents (empty list when no agents)."""
    if not group:
        return []
    lines = ["| Agent | Model | Description |", "| --- | --- | --- |"]
    lines += [f"| `{name}` | {model} | {desc} |" for name, model, _tier, desc in sorted(group)]
    return lines


def render_agents(rows: list[tuple[str, str, str, str]]) -> str:
    # Same root as the rows — see render_commands above.
    canonical = count_inventory(GRIP_DIR)["agents"]
    assert len(rows) == canonical, f"agent rows {len(rows)} != count_inventory {canonical}"
    by_tier: dict[str, list[tuple[str, str, str, str]]] = {tier: [] for tier in TIER_ORDER}
    for r in rows:
        by_tier[r[2]].append(r)
    rendered = {tier: len(group) for tier, group in by_tier.items()}
    canonical_tiers = count_agents_by_tier(GRIP_DIR)
    assert rendered == canonical_tiers, f"agent tiers {rendered} != count_agents_by_tier {canonical_tiers}"
    out = [
        "# GRIP Agents",
        "",
        _AUTOGEN,
        "",
        f"**{len(rows)} agents** — every `agents/**/*.md`, subfolders included, as Claude Code "
        "loads them, minus `CLAUDE.md` and `_base-protocol.md`, the shared gate protocol the "
        "agents link to (count from `lib/asset_counter.py`). Model + tier come from each "
        "agent's frontmatter (`-` = field absent), and each heading counts its tier. "
        "Budget/savings dropped (R0).",
    ]
    for tier in TIER_ORDER:
        group = by_tier[tier]
        if not group:
            continue
        out += ["", f"## {tier.capitalize()} ({len(group)})", ""]
        out += _agent_table(group)
    out += ["", f"<!-- generated: {len(rows)} agents · v{grip_version()} · source agents/**/*.md -->", ""]
    return "\n".join(out)


def _first_difference(committed: str, generated: str) -> str | None:
    """Name the first line where two renderings diverge, quoting both sides.

    Absorbed from the DeepSeek Harness's ``scripts/gen-tool-catalog.ts
    --check``, whose failure output names the line number and prints the
    committed and generated text JSON-quoted. GRIP's ``--check`` printed only
    a filename, so a CI failure said "COMMANDS.md is stale" and nothing more —
    diagnosing it meant regenerating locally and reading a git diff. This makes
    the failure message the diagnosis.

    Returns ``None`` when the two are identical.
    """
    c_lines, g_lines = committed.splitlines(), generated.splitlines()
    for i in range(max(len(c_lines), len(g_lines))):
        c = c_lines[i] if i < len(c_lines) else None
        g = g_lines[i] if i < len(g_lines) else None
        if c != g:
            # ensure_ascii=False: the docs are full of em-dashes, and "\\u2014" in a
            # failure message is noise the reader has to decode.
            quote = lambda v: json.dumps(v, ensure_ascii=False) if v is not None else "<end of file>"  # noqa: E731
            return (
                f"  first difference at line {i + 1}\n"
                f"    committed: {quote(c)}\n"
                f"    generated: {quote(g)}"
            )
    return None


def _check(targets: dict) -> int:
    """Compare every committed target against a fresh in-memory render."""
    problems = []
    for path, text in targets.items():
        if not path.exists():
            problems.append(f"{path.name}: MISSING")
            continue
        committed = path.read_text(encoding="utf-8")
        if committed != text:
            detail = _first_difference(committed, text)
            problems.append(f"{path.name}: STALE\n{detail}" if detail else f"{path.name}: STALE")
    if not problems:
        print("reference docs up to date")
        return 0
    print("STALE -- run scripts/generate-reference-docs.py")
    for problem in problems:
        print(problem)
    return 1


def main() -> int:
    docs = GRIP_DIR / "docs"
    targets = {
        docs / "COMMANDS.md": render_commands(collect_commands()),
        docs / "AGENTS.md": render_agents(collect_agents()),
    }

    if "--stdout" in sys.argv:
        for path, text in targets.items():
            print(f"\n===== {path.name} =====\n{text}")
        return 0

    if "--check" in sys.argv:
        return _check(targets)

    for path, text in targets.items():
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(GRIP_DIR)} ({text.count(chr(10))} lines)")
    # Keep the README's grip-stats markers in sync with the same counter.
    if refresh_readme_markers():
        print("refreshed README.md inventory markers")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
